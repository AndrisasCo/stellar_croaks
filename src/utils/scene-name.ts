/**
 * Имя биопода (`Scene.name`) — то, что игрок видит в шапке списка жаб, в «О секторе»
 * и в списке переезда.
 *
 * Правило одно на все места правки (вкладки «Статистика» и «О секторе»): имя
 * обрезается по краям, а пробелы и переносы строк внутри схлопываются в один.
 * Пустое имя не сохраняется — иначе биопод потерял бы подпись во всех списках.
 */
export const SCENE_NAME_MAX_LENGTH = 24;

/**
 * Привести введённое имя к виду, в котором оно сохранится.
 *
 * @returns имя без лишних пробелов или `null`, если сохранять нечего (пустой ввод).
 */
export const normalizeSceneName = (raw: string): string | null => {
  const name = raw
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, SCENE_NAME_MAX_LENGTH)
    .trim();

  return name.length > 0 ? name : null;
};
