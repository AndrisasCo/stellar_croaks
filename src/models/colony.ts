/**
 * Состояние колонии: сектора, которые игрок возвёл сам на гексагональной карте.
 *
 * Базовые секторы (ядро и биопод) считаются построенными всегда и в сохранении не лежат —
 * так старые сейвы остаются валидными, а карта не ломается. Репродуктора среди базовых нет:
 * первый игрок строит сам, бесплатно (`firstFree` в каталоге).
 *
 * Каталог построек (цвет, цена, «единственная в колонии», действия) живёт в
 * `components/HexMap/rooms-config.ts` — модель хранит только вид сектора и время постройки.
 */

/**
 * Виды секторов, которые игрок может построить на свободном гексе карты.
 *
 * «Ядро» сюда не входит: оно стоит в центре колонии с самого начала. Коллайдер, Торговая Капсула
 * и диссоциатор строятся в единственном экземпляре (флаг `unique` в черновике сектора),
 * остальные виды — сколько угодно раз.
 */
export type ColonyRoomKind =
  | "aviary"
  | "breeding"
  | "collider"
  | "scout"
  | "storage"
  | "shop"
  | "hospital"
  | "dissociator"
  | "power";

export interface ColonyRoomState {
  /**
   * Канонический id постройки — `вид_уникальноеЧисло`. Карта адресует тот же сектор по
   * id гекса (`slotId`): жаба помнит место по `RoomConfig.id`, а сейв — по этому id.
   */
  id: string;
  /**
   * id гекса карты (`RoomConfig.slotId`), на котором стоит постройка. Сам гекс сохраняет
   * прежний id (`slot-north`, `aviary`), а сектор получает новый `id` вида `вид_число`.
   * У старых сейвов поля нет — тогда id постройки и был id гекса.
   */
  slotId?: string;
  kind: ColonyRoomKind;
  /** Когда сектор была построена. */
  builtAt: string;
  /**
   * Биопод-сектор: id биопода (`Scene`), который она открыла.
   * Раньше биоподы покупали в Торговая Капсулае, теперь каждый построенный на гексе «Биопод»
   * создаёт свой биопод с местами для жаб (см. `backend/colony.ts`).
   */
  sceneId?: number;
}

/** Ключи апгрейдов сектора: сам факт покупки (см. `utils/room-upgrades.ts`). */
export type RoomUpgradeKey =
  | "autoFeeder"
  | "autoBreeder"
  | "distributor"
  | "repatriator"
  | "quarantineCatcher";

/**
 * Апгрейды сектора: автокормушка, а в Репродукторе — «Инициатор» (автоухаживание)
 * и «Распределитель» (перенос головастиков в биоподы), в Медотсеке — репатриатор
 * и карантин-уловитель.
 *
 * Апгрейд принадлежит сектору (гексу), а не биоподу: улучшить можно любой сектор, где живут
 * жабы — и «Био Под», и ⚡-энергосектор, и Медотсек (`components/HexMap/rooms-config.ts` →
 * `isToadRoom`), поэтому он хранится по id гекса, а не в `Scene` (у энергосектора биопода нет
 * вовсе).
 *
 * У каждого апгрейда два поля: `<ключ>` — куплен ли он, и `<ключ>Enabled` — включён ли
 * сейчас. После покупки апгрейд включён (`Enabled` не пишется или `true`), а выключить его
 * игрок может переключателем в «Данных сектора». Старые сейвы поля `Enabled` не знают —
 * для них апгрейд тоже считается включённым (`utils/room-upgrades.ts` → `isUpgradeActive`).
 */
export interface RoomUpgrades {
  /** Автокормушка: жабы сектора едят со склада сами (см. `utils/auto-feeder.ts`). */
  autoFeeder?: boolean;
  /** Автокормушка включена: выключенная покупка остаётся, но не кормит. */
  autoFeederEnabled?: boolean;
  /**
   * «Инициатор»: Репродуктор сам запускает ухаживание, когда в паре есть самец
   * и самка и выполнены условия (`utils/breeding-manager.ts`).
   */
  autoBreeder?: boolean;
  /** «Инициатор» включён: выключенная покупка остаётся, но ухаживание не запускает. */
  autoBreederEnabled?: boolean;
  /**
   * «Распределитель»: Репродуктор сам отправляет головастиков в свободные биоподы
   * (`utils/nest-distributor.ts`). Без него головастики остаются в секторе, пока
   * игрок не перенесёт их вручную.
   */
  distributor?: boolean;
  /** «Распределитель» включён: выключенная покупка остаётся, но головастиков не переносит. */
  distributorEnabled?: boolean;
  /**
   * Репатриатор: Медотсек сам отправляет выздоровевших жаб домой
   * (см. `utils/repatriator.ts`).
   */
  repatriator?: boolean;
  /** Репатриатор включён: выключенная покупка остаётся, но жаб не выписывает. */
  repatriatorEnabled?: boolean;
  /**
   * Карантин-уловитель: Медотсек сам забирает заболевших жаб на свободные койки
   * (см. `utils/quarantine-catcher.ts`).
   */
  quarantineCatcher?: boolean;
  /** Карантин-уловитель включён: выключенная покупка остаётся, но больных не трогает. */
  quarantineCatcherEnabled?: boolean;
}

/** Сектор без апгрейдов: общий пустой ответ (объект не мутируется). */
export const EMPTY_UPGRADES: RoomUpgrades = {};

export interface ColonyState {
  rooms: ColonyRoomState[];
  /** Апгрейды секторов по id гекса: `{ aviary: { autoFeeder: true } }`. */
  upgrades?: Record<string, RoomUpgrades>;
  /**
   * Гексы снесённых секторов: id слота, оставшегося без сектора. Снос сектора — деньги на
   * ветер, но не потеря земли: гекс остаётся на карте свободным слотом, и его фронт
   * (`getUnlockedRooms`) продолжает держать открытыми гексы, которые от него выросли.
   *
   * Нужен и для базового биопода: он стоит с начала игры и в `rooms` не лежит, поэтому снос
   * ему не спишешь простым удалением — его отсутствие помнит этот список.
   * Гекс застраивают заново — метка снимается (`backend/colony.ts` → `buildColonyRoom`).
   * Ядро снести нельзя, его id сюда не попадает.
   */
  demolished?: string[];
}

/** Пустая колония: ничего не построено. Базовые ядро и биопод на карте есть всегда. */
export const EMPTY_COLONY: ColonyState = { rooms: [] };
